/// <reference types="bun-types" />
import { existsSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { resolve, dirname } from "node:path";

export interface ReleaseInfo {
  id: string;
  version: string;
  channel: string;
  release_date: string;
  download_url: string;
  changelog: string;
  min_version: string;
  sha256: string;
  is_latest: boolean;
  published_at: number;
}

const DEFAULT_FALLBACK: ReleaseInfo = {
  id: "release-1.3.0",
  version: "1.3.0",
  channel: "stable",
  release_date: "2026-09-27",
  download_url:
    "https://github.com/ceybyte/cbpos-releases/releases/download/v1.3.0/CBPOSSetup-1.3.0.exe",
  changelog:
    "Initial stable public release with trilingual receipt printing, VAT/SSCL calculation, and offline SQLite storage.",
  min_version: "1.0.0",
  sha256: "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855",
  is_latest: true,
  published_at: 1758931200000,
};

export async function snapshotRelease(options?: {
  releasesJsonPath?: string;
  outputPath?: string;
}): Promise<ReleaseInfo> {
  const root = resolve(__dirname, "..");
  const releasesPath =
    options?.releasesJsonPath ??
    resolve(root, "apps/web/.content/releases.json");
  const outputPath =
    options?.outputPath ??
    resolve(root, "apps/api/src/lib/fallback-release.ts");

  let release: ReleaseInfo = DEFAULT_FALLBACK;

  if (existsSync(releasesPath)) {
    try {
      const releases: any[] = JSON.parse(readFileSync(releasesPath, "utf-8"));
      const latest =
        releases.find((r) => r.is_latest && !r.is_yanked) ||
        releases.find((r) => !r.is_yanked) ||
        releases[0];

      if (latest) {
        release = {
          id: latest.id || DEFAULT_FALLBACK.id,
          version: latest.version || DEFAULT_FALLBACK.version,
          channel: latest.channel || "stable",
          release_date: latest.release_date || DEFAULT_FALLBACK.release_date,
          download_url: latest.download_url || DEFAULT_FALLBACK.download_url,
          changelog: latest.changelog || DEFAULT_FALLBACK.changelog,
          min_version: latest.min_version || "1.0.0",
          sha256: latest.sha256 || DEFAULT_FALLBACK.sha256,
          is_latest: Boolean(latest.is_latest),
          published_at: Number(latest.published_at) || Date.now(),
        };
      }
    } catch (e) {
      console.warn("Could not parse releases.json, using default fallback:", e);
    }
  }

  const outDir = dirname(outputPath);
  if (!existsSync(outDir)) {
    mkdirSync(outDir, { recursive: true });
  }

  const fileContent = `/**
 * AUTO-GENERATED by scripts/snapshot-release.ts. DO NOT EDIT DIRECTLY.
 * Embedded in Worker bundle for $0/month zero-D1-query responses.
 */

export interface ReleaseInfo {
  id: string;
  version: string;
  channel: string;
  release_date: string;
  download_url: string;
  changelog: string;
  min_version: string;
  sha256: string;
  is_latest: boolean;
  published_at: number;
}

export const FALLBACK_RELEASE: ReleaseInfo = ${JSON.stringify(release, null, 2)};
`;

  writeFileSync(outputPath, fileContent, "utf-8");
  console.log(`✓ Generated ${outputPath} (version ${release.version})`);

  return release;
}

if (import.meta.main) {
  snapshotRelease().catch((err) => {
    console.error("Failed to snapshot release:", err);
    process.exit(1);
  });
}
