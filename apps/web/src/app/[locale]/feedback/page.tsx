import type { Metadata } from "next";
import { setRequestLocale } from "next-intl/server";
import { routing } from "@/i18n/routing";
import { buildMetadata } from "@/lib/metadata";
import { FeedbackBoard } from "@/features/feedback/components/FeedbackBoard";

export function generateStaticParams() {
  return routing.locales.map((locale) => ({ locale }));
}

export async function generateMetadata({
  params,
}: {
  params: Promise<{ locale: string }>;
}): Promise<Metadata> {
  const { locale } = await params;
  return buildMetadata({
    locale,
    path: "/feedback",
    title: "Feedback Tracker",
    description:
      "Public bug and feature tracker for CB POS. Submit issues, suggest features, and track development progress in Sri Lanka.",
  });
}

export default async function FeedbackPage({
  params,
}: {
  params: Promise<{ locale: string }>;
}) {
  const { locale } = await params;
  setRequestLocale(locale);

  return <FeedbackBoard locale={locale} />;
}
